//! The message **keys**: variant names are code, text is data.
//!
//! One row = one variant. The wording lives in `locales/<lang>.rs` — one
//! file per language, each an exhaustive `match`, so the compiler rejects a
//! half-translated locale and a new [`crate::Locale`] cannot skip its file.
//!
//! # Naming
//!
//! The prefix says where it appears, not what it means: `Menu*` (menu tree),
//! `Ctx*` (context menu), `Win*` (window system menu), `Status*` (status bar),
//! `Prefs*` (preferences), `Dlg*` (dialogs). The same word in two places gets
//! two keys — "File" is not necessarily one word across a menu and a dialog.
//! The exception is **one command** appearing in several places: one UI
//! element, one key.
//!
//! # Editing text
//!
//! Edit `locales/<lang>.rs`; never rename a key for wording's sake (keys are
//! code references). A new row gets a prefix matching where it appears and a
//! column in **every** locale file.
//!
//! # Placeholders
//!
//! A `Fmt` field name is the `format!` placeholder, and word order may differ
//! per locale: the arguments live in the struct, so each language writes its
//! own syntax. That is why a message is a typed value, not a template string.

